def overlord_count_for_wave(wave: int) -> int:
    """Wave 15..19 -> 1, Wave 20..24 -> 2, Wave 25..29 -> 3, +1 every 5 rounds."""
    if wave < 15:
        return 0
    if wave < 20:
        return 1
    return 2 + (wave - 20) // 5


